// Records the real stdout/stderr of `make demo` and `make demo-compaction` with
// timestamps, so the landing page can replay them. Output is written to
// site/recordings.js. Both demos use a scripted model; no API key is involved.
import path from "node:path";

const ROOT = path.resolve(import.meta.dir, "..");
const OUT = path.join(ROOT, "site", "recordings.js");
const DEMOS = [
  { id: "bugfix", target: "demo", title: "Bug fix with a sub-agent" },
  { id: "compaction", target: "demo-compaction", title: "Context compaction" },
] as const;

type Chunk = [number, string]; // [milliseconds since start, text]

async function record(target: string): Promise<{ events: Chunk[]; exitCode: number; durationMs: number }> {
  const started = performance.now();
  const events: Chunk[] = [];
  const proc = Bun.spawn(["make", target], { cwd: ROOT, stdout: "pipe", stderr: "pipe" });
  const pump = async (stream: ReadableStream<Uint8Array>) => {
    const decoder = new TextDecoder();
    for await (const bytes of stream) {
      events.push([Math.round(performance.now() - started), decoder.decode(bytes, { stream: true })]);
    }
  };
  await Promise.all([pump(proc.stdout), pump(proc.stderr)]);
  const exitCode = await proc.exited;
  return { events, exitCode, durationMs: Math.round(performance.now() - started) };
}

const recordings = [];
for (const demo of DEMOS) {
  const run = await record(demo.target);
  if (run.exitCode !== 0) throw new Error(`make ${demo.target} exited with ${run.exitCode}`);
  recordings.push({ ...demo, command: `make ${demo.target}`, ...run });
  console.error(`${demo.target}: ${run.events.length} chunks, ${run.durationMs} ms, exit ${run.exitCode}`);
}

const header = "// Generated by scripts/record-demos.ts from the real `make demo` and `make demo-compaction` output.\n";
await Bun.write(OUT, `${header}window.QUILL_RECORDINGS = ${JSON.stringify({ recordedOn: new Date().toISOString().slice(0, 10), demos: recordings }, null, 1)};\n`);
console.error(`wrote ${path.relative(ROOT, OUT)}`);
